"""Regenerate CONVENTIONS.md from the .cursor/rules/*.mdc files (the source of truth)."""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RULES_DIR = ROOT / ".cursor" / "rules"
OUTPUT = ROOT / "CONVENTIONS.md"

# Reading order for humans; any rule file not listed is appended alphabetically.
ORDER = [
    "general", "design", "selfcal-domain", "casa-io", "implementation", "naming", "documentation",
    "error-handling", "testing", "cicd"
]

FRONTMATTER = re.compile(r"\A---\n(.*?)\n---\n", re.DOTALL)


def read_rule(path: Path) -> tuple[str, str]:
    text = path.read_text(encoding="utf-8")
    match = FRONTMATTER.match(text)
    if match is None:
        raise ValueError(f"{path} has no frontmatter")
    description = re.search(r"^description:\s*(.+)$", match.group(1), re.MULTILINE)
    return (description.group(1).strip() if description else path.stem), text[match.end():].strip()


def demote_headings(body: str) -> str:
    # CONVENTIONS.md has a single H1, so each rule's headings move down one level.
    lines, in_fence = [], False
    for line in body.splitlines():
        if line.startswith("```"):
            in_fence = not in_fence
        lines.append("#" + line if not in_fence and line.startswith("#") else line)
    return "\n".join(lines)


def build_conventions() -> str:
    paths = {p.stem: p for p in RULES_DIR.glob("*.mdc")}
    ordered = [name for name in ORDER if name in paths] + sorted(set(paths) - set(ORDER))
    sections = [
        "# wenuray conventions\n\n"
        "<!-- Generated by tools/sync_conventions.py from .cursor/rules/*.mdc. Do not edit by hand. -->"
    ]
    for name in ordered:
        description, body = read_rule(paths[name])
        sections.append(f"<!-- {name}.mdc: {description} -->\n\n{demote_headings(body)}")
    return "\n\n---\n\n".join(sections) + "\n"


def main() -> int:
    content = build_conventions()
    if "--check" in sys.argv:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != content:
            print("CONVENTIONS.md is out of date; run python tools/sync_conventions.py")
            return 1
        return 0
    OUTPUT.write_text(content, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
